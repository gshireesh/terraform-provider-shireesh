	b.WriteString("func (s *InMemoryServer) Start(ctx context.Context) (*httptest.Server, string, error) {\n")
	b.WriteString("\t// gRPC on random port\n")
	b.WriteString("\tlis, err := net.Listen(\"tcp\", \"127.0.0.1:0\")\n")
	b.WriteString("\tif err != nil { return nil, \"\", err }\n")
	b.WriteString("\tgrpcSrv := grpc.NewServer(grpc.Creds(insecure.NewCredentials()))\n")
	b.WriteString("\tapi.RegisterGrpcTerraformServiceServer(grpcSrv, s)\n")
	b.WriteString("\treflection.Register(grpcSrv)\n")
	b.WriteString("\tgo grpcSrv.Serve(lis)\n")
	b.WriteString("\tgrpcTarget := lis.Addr().String()\n")
	b.WriteString("\t// HTTP JSON gateway mux that proxies to the same server\n")
	b.WriteString("\tglue := runtime.NewServeMux()\n")
	b.WriteString("\tcc, err := grpc.DialContext(ctx, grpcTarget, grpc.WithTransportCredentials(insecure.NewCredentials()))\n")
	b.WriteString("\tif err != nil { return nil, \"\", err }\n")
	b.WriteString("\tif err := api.RegisterGrpcTerraformServiceHandlerClient(ctx, glue, api.NewGrpcTerraformServiceClient(cc)); err != nil { return nil, \"\", err }\n")
