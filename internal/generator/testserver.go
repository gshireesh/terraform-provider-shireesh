		b.WriteString("\tif req == nil || req.Id == \"\" { return &api." + pname + "ReadResponse{}, nil }\n")
		b.WriteString(fmt.Sprintf("\tif it, ok := s.%s[req.Id]; ok {\n", store))
		b.WriteString(fmt.Sprintf("\t\treturn &api.%sReadResponse{Item: &api.%sReadOutput{\n\t\t\tId: it.Id,\n", pname, pname))
		for _, f := range s.Fields {
			if f.Name == "id" {
				continue
			}
			b.WriteString(fmt.Sprintf("\t\t\t%s: it.%s,\n", pascal(f.Name), pascal(f.Name)))
		}
		b.WriteString("\t\t}}, nil\n\t}\n")
		b.WriteString(fmt.Sprintf("\treturn &api.%sReadResponse{}, nil\n}\n\n", pname))
		// Update
		b.WriteString(fmt.Sprintf("func (s *InMemoryServer) %sUpdate(ctx context.Context, req *api.%sUpdateRequest) (*api.%sUpdateResponse, error) {\n", pname, pname, pname))
