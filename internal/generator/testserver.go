		for _, f := range s.Fields {
			if f.Name == "id" {
				continue
			}
			b.WriteString(fmt.Sprintf("\t\tit.%s = req.Item.%s\n", pascal(f.Name), pascal(f.Name)))
		}
		b.WriteString("\t}\n")
		b.WriteString(fmt.Sprintf("\tout := &api.%sUpdateOutput{\n\t\tId: it.Id,\n", pname))
		for _, f := range s.Fields {
			if f.Name == "id" {
				continue
			}
			b.WriteString(fmt.Sprintf("\t\t%s: it.%s,\n", pascal(f.Name), pascal(f.Name)))
		}
		b.WriteString("\t}\n")
